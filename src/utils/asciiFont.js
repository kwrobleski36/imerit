// Pad each glyph to consistent height of 4 rows with consistent column widths within the glyph
function normalizeGlyph(g) {
  if (!g) return ['    ', '    ', '    ', '    ']
  const w = Math.max(...g.map(r => r.length))
  return g.map(r => r.padEnd(w, ' '))
}

export function nameToAscii(name) {
  if (!name) return ''
  const chars = name.toUpperCase().split('')
  const rows = [[], [], [], []]
  for (const ch of chars) {
    const glyph = normalizeGlyph(FONT[ch] ?? FONT[' '])
    for (let r = 0; r < 4; r++) rows[r].push(glyph[r])
  }
  return rows.map(r => r.join(' ')).join('\n')
}
